"""`contracts generate` — build registry.md from source (S1, S3, S4).

Walks the configured source trees, extracts call sites with ast (no regex),
resolves each call target to a `module:qualname` interface identifier, and
writes registry.md with:

  - per-interface sections: direction, authority, call sites (file + symbol)
  - an explicit "Unresolved" section for call targets that cannot be
    established statically (dynamic dispatch, instance attributes, targets
    outside the source trees, ...)
  - stable, byte-deterministic ordering (interfaces sorted; call sites sorted
    by file then enclosing symbol; line numbers deliberately excluded so
    unrelated edits do not churn the registry)

Resolution model (Python extractor: stdlib ast only; TypeScript extractor:
tree-sitter — see ts_extract.py, registered when tree-sitter is installed):
  - `import mod` / `import mod as m` + `mod.fn()` / `m.sub.fn()`  → mod.sub:fn
  - `from mod import fn` / `from mod import fn as f` + `fn()`     → mod:fn
  - calls to top-level names defined in the same module            → mod:qual
  - everything else (obj.method(), locals, builtins)               → Unresolved

Direction/authority come from config patterns ([inputs]/[outputs]/[lax]/
[rigid]) matched with fnmatch against `module:qualname` identifiers. The two
axes are independent: an interface may be input and rigid. Defaults: internal
and lax.
"""

from __future__ import annotations

import ast
import fnmatch
import sys
from dataclasses import dataclass, field
from pathlib import Path

from . import config as config_mod
from .cli import EXIT_FAIL, EXIT_OK, find_repo_root
from .resolutions import ResolutionError, load_resolutions

REGISTRY_NAME = "registry.md"

_HEADER = (
    "# Interface registry\n\n"
    "<!-- Generated by `contracts generate`. Never edit by hand (S9). -->\n"
)

_DEF_NODES = (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)


@dataclass(frozen=True)
class CallSite:
    file: str  # repo-relative posix path
    symbol: str  # enclosing definition qualname, "<module>" for top level


@dataclass
class Interface:
    direction: str = "internal"
    authority: str = "lax"
    call_sites: set[CallSite] = field(default_factory=set)


@dataclass
class UnresolvedTarget:
    call_sites: set[CallSite] = field(default_factory=set)


class _ModuleIndex:
    """Per-module symbol table and import bindings, built from ast."""

    def __init__(self) -> None:
        self.defs: dict[str, set[str]] = {}  # module -> top-level names
        self.imports: dict[str, dict[str, str]] = {}  # module -> alias binding

    def add(self, module: str, tree: ast.AST) -> None:
        defs: set[str] = set()
        binds: dict[str, str] = {}
        for node in tree.body:  # top-level only: matches the resolution model
            if isinstance(node, _DEF_NODES):
                defs.add(node.name)
            elif isinstance(node, ast.Import):
                for alias in node.names:
                    binds[alias.asname or alias.name.split(".")[0]] = alias.name
            elif isinstance(node, ast.ImportFrom):
                if node.module and node.level == 0:
                    for alias in node.names:
                        binds[alias.asname or alias.name] = f"{node.module}:{alias.name}"
        self.defs[module] = defs
        self.imports[module] = binds

    def resolve(self, chain: list[str], module: str) -> str | None:
        """Resolve a dotted call chain to `module:qualname`, or None."""
        root, rest = chain[0], chain[1:]
        binding = self.imports.get(module, {}).get(root)
        if binding is not None:
            if ":" in binding:  # from mod import name
                return binding + ("." + ".".join(rest) if rest else "")
            return binding + (":" + ".".join(rest) if rest else "")  # import mod [as alias]
        if root in self.defs.get(module, set()):
            return module + ":" + ".".join(chain)
        return None


def _module_of(base: Path, file: Path) -> str:
    """Dotted module path of `file` relative to its source-tree `base`."""
    rel = file.relative_to(base).with_suffix("")
    parts = list(rel.parts)
    if parts and parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _callee_chain(node: ast.AST) -> list[str] | None:
    """Flatten a Name/Attribute chain into dotted parts; None if not one."""
    parts: list[str] = []
    while isinstance(node, ast.Attribute):
        parts.append(node.attr)
        node = node.value
    if isinstance(node, ast.Name):
        parts.append(node.id)
        return list(reversed(parts))
    return None  # instance attribute, subscript, call result, ...


def _classify(identifier: str, cfg: config_mod.Config) -> tuple[str, str]:
    direction, authority = "internal", "lax"
    for axis, value in (
        ("inputs", "input"),
        ("outputs", "output"),
        ("lax", "lax"),
        ("rigid", "rigid"),
    ):
        if any(fnmatch.fnmatchcase(identifier, p) for p in getattr(cfg, axis)):
            if axis in ("inputs", "outputs"):
                direction = value
            else:
                authority = value
    return direction, authority


class Extractor:
    """A language extractor: collects interfaces and unresolved targets
    from the source files its extensions claim (S1 boundary).

    `collect` receives the claimed files as (rel, path, base) tuples and
    returns (interfaces, unresolved, in_tree) where in_tree is the set of
    module names (and dotted prefixes) the extractor actually parsed — used
    for the S3 rigid default.
    """

    def __init__(self, extensions: tuple[str, ...], collect) -> None:
        self.extensions = frozenset(extensions)
        self.collect = collect


_EXTRACTORS: list[Extractor] = [
    Extractor(extensions=(".py",), collect=None),  # filled in below
]


def _extractor_for(suffix: str) -> Extractor | None:
    """Extension-to-extractor dispatch: first registered extractor wins."""
    for extractor in _EXTRACTORS:
        if suffix in extractor.extensions:
            return extractor
    return None


def _claim_files(repo_root: Path, cfg: config_mod.Config) -> dict[Extractor, list[tuple[str, Path, Path]]]:
    """Walk the source trees and group files by their owning extractor."""
    groups: dict[Extractor, list[tuple[str, Path, Path]]] = {}
    for tree in cfg.source_trees:
        base = repo_root / tree
        if base.is_dir():
            for f in sorted(base.rglob("*")):
                if not f.is_file():
                    continue
                extractor = _extractor_for(f.suffix)
                if extractor is None:  # unclaimed extensions are skipped
                    continue
                groups.setdefault(extractor, []).append(
                    (f.relative_to(repo_root).as_posix(), f, base)
                )
    for files in groups.values():
        files.sort()
    return groups


def _collect(repo_root: Path, cfg: config_mod.Config):
    """Return (interfaces, unresolved): each extractor collects over the
    files its extensions claim; results are merged across extractors."""
    interfaces: dict[str, Interface] = {}
    unresolved: dict[str, UnresolvedTarget] = {}
    in_tree: set[str] = set()
    claimed = _claim_files(repo_root, cfg)  # hoisted: one walk for all extractors
    for extractor in _EXTRACTORS:
        files = claimed.get(extractor, [])
        if not files:
            continue
        ex_ifaces, ex_unresolved, ex_in_tree = extractor.collect(repo_root, files)
        for ident, iface in ex_ifaces.items():
            interfaces.setdefault(ident, Interface()).call_sites |= iface.call_sites
        for target, site in ex_unresolved.items():
            unresolved.setdefault(target, UnresolvedTarget()).call_sites |= site.call_sites
        in_tree |= ex_in_tree

    in_tree = _in_tree_module_prefixes(in_tree)
    for ident, iface in interfaces.items():
        iface.direction, iface.authority = _classify(ident, cfg)
        if ident.split(":")[0] not in in_tree:
            iface.authority = "rigid"  # S3: outside the source trees defaults to rigid
    return interfaces, unresolved


def _collect_python(repo_root: Path, files: list[tuple[str, Path, Path]]):
    """Python extractor (stdlib ast): resolve call targets via imports
    and same-module definitions."""
    index = _ModuleIndex()
    modules: dict[str, ast.AST] = {}
    for rel, path, base in files:
        module = _module_of(base, path)
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=rel)
        modules[module] = tree
        index.add(module, tree)

    interfaces: dict[str, Interface] = {}
    unresolved: dict[str, UnresolvedTarget] = {}

    for rel, path, base in files:
        module = _module_of(base, path)
        _walk(modules[module], [], module, rel, index, interfaces, unresolved)
    return interfaces, unresolved, _in_tree_module_prefixes(set(modules))


_EXTRACTORS[0] = Extractor(extensions=(".py",), collect=_collect_python)


def _register_ts() -> None:
    """Register the TypeScript extractor when tree-sitter is available;
    without it the substrate stays Python-only (lazy import, no hard dep)."""
    try:
        import tree_sitter  # noqa: F401  real availability probe (R2.F1):
    except ImportError:   # ts_extract defers its own imports to collect time
        return
    try:
        from . import ts_extract
    except ImportError:
        return
    _EXTRACTORS.append(Extractor(extensions=(".ts", ".tsx"), collect=ts_extract.collect))


_register_ts()


def apply_resolutions(interfaces: dict[str, Interface],
                      unresolved: dict[str, UnresolvedTarget],
                      resolutions) -> None:
    """Apply persisted resolutions in place (S4): move each resolved call
    site from the Unresolved section into its interface, or drop it when
    external. Resolutions naming an unknown target, call site or interface
    fail loudly — a stale resolution is drift, never silently ignored."""
    for r in resolutions:
        sites = unresolved.get(r.target)
        if sites is None:
            raise ResolutionError(
                f"stale resolution: unknown unresolved target [{r.target}]"
            )
        if r.call_site is not None and r.call_site not in sites.call_sites:
            raise ResolutionError(
                f"stale resolution: [{r.target}] has no call site "
                f"{r.call_site.file}:{r.call_site.symbol}"
            )
        if not r.external and r.interface not in interfaces:
            raise ResolutionError(
                f"stale resolution: [{r.target}] names unknown interface "
                f"{r.interface}"
            )
        if r.call_site is None:
            resolved = set(sites.call_sites)
            sites.call_sites.clear()
        else:
            resolved = {r.call_site}
            sites.call_sites.discard(r.call_site)
        if not r.external:
            interfaces[r.interface].call_sites |= resolved
        if not sites.call_sites:
            del unresolved[r.target]


def _in_tree_module_prefixes(modules: dict[str, ast.AST]) -> set[str]:
    """All module names and their dotted ancestor prefixes (packages)."""
    prefixes: set[str] = set()
    for name in modules:
        parts = name.split(".")
        for i in range(1, len(parts) + 1):
            prefixes.add(".".join(parts[:i]))
    return prefixes


def _walk(node: ast.AST, stack: list[str], module: str, rel: str,
          index: _ModuleIndex, interfaces: dict, unresolved: dict) -> None:
    for child in ast.iter_child_nodes(node):
        if isinstance(child, _DEF_NODES):
            _walk(child, stack + [child.name], module, rel, index, interfaces, unresolved)
            continue
        if isinstance(child, ast.Call):
            chain = _callee_chain(child.func)
            ident = index.resolve(chain, module) if chain is not None else None
            site = CallSite(file=rel, symbol=".".join(stack) if stack else "<module>")
            if ident is None:
                key = ".".join(chain) if chain else "<unresolvable>"
                unresolved.setdefault(key, UnresolvedTarget()).call_sites.add(site)
            else:
                interfaces.setdefault(ident, Interface()).call_sites.add(site)
        _walk(child, stack, module, rel, index, interfaces, unresolved)


def render_registry(interfaces: dict[str, Interface],
                    unresolved: dict[str, UnresolvedTarget]) -> str:
    """Deterministic markdown rendering."""
    lines = [_HEADER]
    if interfaces:
        lines.append("## Interfaces\n")
        for ident in sorted(interfaces):
            iface = interfaces[ident]
            lines.append(f"### {ident}\n")
            lines.append(f"- direction: {iface.direction}")
            lines.append(f"- authority: {iface.authority}")
            lines.append("- call sites:")
            for site in sorted(iface.call_sites, key=lambda s: (s.file, s.symbol)):
                lines.append(f"  - {site.file}:{site.symbol}")
            lines.append("")
    lines.append("## Unresolved\n")
    if unresolved:
        for target in sorted(unresolved):
            lines.append(f"### {target}\n")
            lines.append("- call sites:")
            for site in sorted(unresolved[target].call_sites, key=lambda s: (s.file, s.symbol)):
                lines.append(f"  - {site.file}:{site.symbol}")
            lines.append("")
    else:
        lines.append("(none)\n")
    return "\n".join(lines) + "\n"


def _generate_full(repo_root: Path, cfg: config_mod.Config) -> tuple[str, dict, dict]:
    """Render the registry text and return it with the resolved
    (interfaces, unresolved) maps, so callers that need the counts do not
    have to re-run the extraction pass."""
    interfaces, unresolved = _collect(repo_root, cfg)
    apply_resolutions(interfaces, unresolved, load_resolutions(repo_root))
    return render_registry(interfaces, unresolved), interfaces, unresolved


def generate(repo_root: Path, cfg: config_mod.Config) -> str:
    return _generate_full(repo_root, cfg)[0]


def main_generate(args) -> int:
    root = find_repo_root()
    try:
        text, interfaces, unresolved = _generate_full(root, args.config)
    except ResolutionError as exc:
        print(f"contracts generate: {exc}", file=sys.stderr)
        return EXIT_FAIL
    (root / REGISTRY_NAME).write_text(text, encoding="utf-8")
    print(
        f"registry written: {REGISTRY_NAME} "
        f"({len(interfaces)} interfaces, {len(unresolved)} unresolved targets)"
    )
    return EXIT_OK
